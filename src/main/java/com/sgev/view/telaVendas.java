    private void txtCodigoBarrasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtCodigoBarrasActionPerformed
   String codigoDigitado = txtCodigoBarras.getText().trim();
    
    if (!codigoDigitado.isEmpty()) {
        com.sgev.dao.ProdutoDAO dao = new com.sgev.dao.ProdutoDAO();
        com.sgev.model.Produto p = dao.buscarPorCodigo(codigoDigitado);
        
        if (p != null) {
            String qtdString = javax.swing.JOptionPane.showInputDialog(this, 
                    "Digite a quantidade para " + p.getNome() + ":", "Quantidade", 
                    javax.swing.JOptionPane.QUESTION_MESSAGE);

            if (qtdString != null && !qtdString.isEmpty()) {
                try {
                    int qtd = Integer.parseInt(qtdString);
                    double precoUnitario = p.getPrecoVenda().doubleValue();
                    
                    // O Subtotal será usado apenas para a função somarTotalTabela()
                    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tabelaResumoCompras.getModel();
                    
                    // CORREÇÃO DA ORDEM DAS COLUNAS:
                    modelo.addRow(new Object[]{
                        p.getNome(),       // Coluna 0: ITEM
                        qtd,               // Coluna 1: QUANTIDADE
                        precoUnitario,     // Coluna 2: PREÇO (Unitário)
                        p.getValidade()    // Coluna 3: VALIDADE (Agora o subtotal não vai mais para cá)
                    });

                    txtCodigoBarras.setText("");
                    txtCodigoBarras.requestFocus();
                    somarTotalTabela(); // Esta função precisa calcular (Preço * Quantidade)
                    
                } catch (NumberFormatException e) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Erro: Digite um número inteiro para a quantidade.");
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Produto não encontrado!");
        }
    }
    }//GEN-LAST:event_txtCodigoBarrasActionPerformed

    private void somarTotalTabela() {
    double totalGeral = 0;
    for (int i = 0; i < tabelaResumoCompras.getRowCount(); i++) {
        // Pega a quantidade da linha (Coluna 1)
        int qtd = Integer.parseInt(tabelaResumoCompras.getValueAt(i, 1).toString());
        
        // Pega o preço unitário da linha (Coluna 2)
        double precoUnitario = Double.parseDouble(tabelaResumoCompras.getValueAt(i, 2).toString());
        
        // Multiplica e soma ao total
        totalGeral += (qtd * precoUnitario);
    }
    
    // Atualiza o campo de texto do total
    txtTotal.setText(String.format("%.2f", totalGeral));
}
    
    private void iniciarRelogio() {
    // Cria um Timer que executa a cada 1000 milissegundos (1 segundo)
    javax.swing.Timer timer = new javax.swing.Timer(1000, new java.awt.event.ActionListener() {
        @Override
        public void actionPerformed(java.awt.event.ActionEvent e) {
            // Pega a hora atual do sistema
            java.util.Date agora = new java.util.Date();
            // Define o formato: Horas:Minutos:Segundos
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("HH:mm:ss");
            // Atualiza o texto do JLabel
            lblHora.setText(sdf.format(agora));
        }
    });
    timer.start(); // Inicia o relógio
}
    
    
    
    
    
    
    
    
    
    
