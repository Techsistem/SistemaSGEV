    private void btnEmitirCupomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEmitirCupomActionPerformed
        // 1. Verificar se há produtos na lista
    if (tabelaResumoCompras.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Não há produtos para emitir o cupom!");
        return;
    }

    // 2. Montar o corpo do cupom (estilo cupom fiscal)
    StringBuilder cupom = new StringBuilder();
    cupom.append("          SGEV - SISTEMA DE VENDAS          \n");
    cupom.append("--------------------------------------------\n");
    cupom.append("ITEM     QTD      VALOR UN.      TOTAL \n");

    for (int i = 0; i < tabelaResumoCompras.getRowCount(); i++) {
        String nome = tabelaResumoCompras.getValueAt(i, 0).toString();
        String qtd = tabelaResumoCompras.getValueAt(i, 1).toString();
        String preco = tabelaResumoCompras.getValueAt(i, 2).toString();
        cupom.append(String.format("%-10s %-8s %-12s %-10s\n", nome, qtd, preco, preco));
    }

    cupom.append("--------------------------------------------\n");
    cupom.append("VALOR TOTAL: R$ ").append(txtTotal.getText()).append("\n");
    cupom.append("--------------------------------------------\n");
    cupom.append("      OBRIGADO PELA PREFERENCIA!      \n");

    // 3. Criar o arquivo e abrir no Bloco de Notas
    try {
        java.io.File arquivo = new java.io.File("cupom_venda.txt");
        java.io.PrintWriter gravar = new java.io.PrintWriter(arquivo);
        gravar.print(cupom.toString());
        gravar.close();

        // Comando para abrir o arquivo automaticamente no Windows
        java.awt.Desktop.getDesktop().open(arquivo);
        
    } catch (java.io.IOException ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao gerar cupom: " + ex.getMessage());
    }
    }//GEN-LAST:event_btnEmitirCupomActionPerformed

