    private void btnFinalizarCompraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarCompraActionPerformed
        // 1. Verificar se a tabela está vazia antes de finalizar
    if (tabelaResumoCompras.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "A lista de compras está vazia!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Criar uma String para acumular os nomes dos produtos
    StringBuilder listaProdutos = new StringBuilder();
    listaProdutos.append("--- PRODUTOS COMPRADOS ---\n");

    for (int i = 0; i < tabelaResumoCompras.getRowCount(); i++) {
        String nomeProd = tabelaResumoCompras.getValueAt(i, 0).toString(); // Coluna ITEM
        String qtd = tabelaResumoCompras.getValueAt(i, 1).toString();      // Coluna QUANTIDADE
        listaProdutos.append(qtd).append("x - ").append(nomeProd).append("\n");
    }

    // 3. Adicionar o valor total ao final da mensagem
    listaProdutos.append("----------------------------\n");
    listaProdutos.append("TOTAL DA COMPRA: R$ ").append(txtTotal.getText());

    // 4. Exibir o Pop-up com o resumo completo
    javax.swing.JOptionPane.showMessageDialog(this, listaProdutos.toString(), "Venda Finalizada", javax.swing.JOptionPane.INFORMATION_MESSAGE);

    // 5. Limpar a tabela e o total para a próxima venda
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tabelaResumoCompras.getModel();
    modelo.setRowCount(0);
    txtTotal.setText("0,00");
    }//GEN-LAST:event_btnFinalizarCompraActionPerformed

    private void txtPesquisarProdutoKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPesquisarProdutoKeyReleased
        // 1. Pega o termo digitado
    String nomeBusca = txtPesquisarProduto.getText().trim();
    
    // 2. Executa a busca no DAO apenas se o campo não estiver vazio
    if (!nomeBusca.isEmpty()) {
        com.sgev.dao.ProdutoDAO dao = new com.sgev.dao.ProdutoDAO();
        java.util.List<com.sgev.model.Produto> lista = dao.buscarPorNome(nomeBusca);
        
        // 3. Verifica se o usuário apertou ENTER e se encontrou algum produto
        if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_ENTER && !lista.isEmpty()) {
            // Pega o primeiro produto da lista encontrada
            com.sgev.model.Produto p = lista.get(0);
            
            // Adiciona na sua tabela de vendas
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tabelaResumoCompras.getModel();
            modelo.addRow(new Object[]{
                p.getNome(), 
                1, 
                p.getPrecoVenda().doubleValue(), 
                p.getValidade()
            });
            
            // Limpa o campo e atualiza o total
            txtPesquisarProduto.setText("");
            somarTotalTabela(); // Sua função de soma
        }
    }
    }//GEN-LAST:event_txtPesquisarProdutoKeyReleased

