public void listarClientes(String nome) {
    try {
        com.sgev.dao.ClienteDAO dao = new com.sgev.dao.ClienteDAO();
        java.util.List<com.sgev.model.Cliente> lista = dao.buscarPorNome(nome);
        
        // Pega o modelo que já existe na tabela (definido no Design)
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        
        // Limpa apenas as LINHAS, mantendo as colunas
        modelo.setNumRows(0); 

        if (lista != null) {
            for (com.sgev.model.Cliente c : lista) {
                modelo.addRow(new Object[]{
                    c.getId(),
                    c.getNome(),
                    c.getCpf(),
                    c.getTelefone()
                });
            }
        }
        
        // Força a tabela a se redesenhar
        jTable1.revalidate();
        jTable1.repaint();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar tabela: " + e.getMessage());
        e.printStackTrace();
    }
}
