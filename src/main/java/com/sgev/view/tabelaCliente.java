    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
       if (evt.getClickCount() == 2) { // Clique duplo
        int linha = jTable1.getSelectedRow();
        int id = (int) jTable1.getValueAt(linha, 0); // Pega o ID da primeira coluna
        
        // Busca o cliente completo no banco pelo ID
        com.sgev.dao.ClienteDAO dao = new com.sgev.dao.ClienteDAO();
        com.sgev.model.Cliente clienteCompleto = dao.buscarPorId(id); 
        
        if (telaPai != null && clienteCompleto != null) {
            telaPai.carregarDadosCliente(clienteCompleto); // Envia para a tela de edição
            this.dispose(); // Fecha apenas a tabela
        }
    }
    }//GEN-LAST:event_jTable1MouseClicked

